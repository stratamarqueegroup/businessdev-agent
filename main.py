"""
main.py
Business Development Agent v2
"""

import time

from monday import create_item

from config import (
    US_LOCATIONS,
    US_INDUSTRIES,
    EL_SALVADOR_LOCATIONS,
    EL_SALVADOR_INDUSTRIES,
)

from scraper import scrape_businesses
from leads import dedupe_leads
from scoring import score_all
from exporters import export_to_csv
from emailer import send_report_email

MAX_LEADS = 528   # Change to 500 after testing


def run_agent():

    print("=" * 60)
    print("🚀 Strata Marquee Group Business Development Agent")
    print("=" * 60)

    print("\nSearching United States...")
    us_businesses = scrape_businesses(
        US_LOCATIONS,
        US_INDUSTRIES,
    )

    print("\nSearching El Salvador...")
    es_businesses = scrape_businesses(
        EL_SALVADOR_LOCATIONS,
        EL_SALVADOR_INDUSTRIES,
    )

    businesses = us_businesses + es_businesses

    print(f"\nFound {len(businesses)} businesses.")

    businesses = dedupe_leads(businesses)

    print(f"{len(businesses)} unique businesses.")

    businesses = score_all(businesses)

    top_leads = businesses[:MAX_LEADS]

    print(f"\nUploading {len(top_leads)} leads...")

    csv_path = export_to_csv(top_leads)

    uploaded = 0
    failed = 0

    for lead in top_leads:

        notes = f"""
Lead Score: {lead.get('score', 0)}

Reason:
{lead.get('score_reasons', '')}

Generated by Strata Marquee Group AI Agent.
"""

        success = create_item(
            company=lead.get("company", ""),
            address=lead.get("address", ""),
            industry=lead.get("industry", ""),
            phone=lead.get("phone", ""),
            email=lead.get("email", ""),
            website=lead.get("website", ""),
            notes=notes,
        )

        if success:
            uploaded += 1
        else:
            failed += 1

        time.sleep(1)

    print("\n==========================")
    print(f"Uploaded : {uploaded}")
    print(f"Failed   : {failed}")
    print("==========================")

    send_report_email(
        csv_path,
        len(top_leads)
    )

    print("\n✅ Agent run complete.")


if __name__ == "__main__":
    run_agent()